def localize_phase6b_compositions(session: Session) -> Dict[str, Any]:
    """
    Ingests multilingual Bhavartha translations for the 5 pilot compositions across
    Marathi, Bengali, Gujarati, Malayalam, and Odia into database.
    Strictly flags all records as ReviewStatus.DRAFT.
    """
    all_payloads = get_phase6b_localization_payloads()
    results = {}

    translator_provenance = "Platform Multilingual Localization Engine (Editorial Synthesis; Awaiting Native Scholarly Panel)"
    languages_added = ["mr", "bn", "gu", "ml", "or"]

    total_added = 0
    total_updated = 0

    for cid, verses_map in all_payloads.items():
        text_record = session.query(Text).filter_by(content_id=cid).first()
        if not text_record:
            logger.warning(f"Text {cid} not found in database. Skipping.")
            continue

        verse_records = {v.verse_number: v for v in text_record.verses}
        added_count = 0
        updated_count = 0

        for v_num, lang_dict in verses_map.items():
            if v_num not in verse_records:
                continue
            v_obj = verse_records[v_num]

            for lang_code, trans_text in lang_dict.items():
                existing = [
                    t for t in v_obj.translations
                    if t.target_language == lang_code and t.translation_type == TranslationType.BHAVARTHA
                ]
                if existing:
                    existing[0].translated_text = trans_text
                    existing[0].translator = translator_provenance
                    existing[0].review_status = ReviewStatus.DRAFT
                    updated_count += 1
                else:
                    new_tr = Translation(
                        verse_id=v_obj.id,
                        target_language=lang_code,
                        translation_type=TranslationType.BHAVARTHA,
                        translated_text=trans_text,
                        translator=translator_provenance,
                        review_status=ReviewStatus.DRAFT,
                    )
                    v_obj.translations.append(new_tr)
                    added_count += 1

        total_added += added_count
        total_updated += updated_count

        results[cid] = {
            "title": text_record.canonical_title,
            "languages": languages_added,
            "added_translations": added_count,
            "updated_translations": updated_count,
            "review_status": "DRAFT",
        }

    session.commit()
    results["summary"] = {
        "total_added": total_added,
        "total_updated": total_updated,
        "languages": languages_added,
    }
    return results


if __name__ == "__main__":
    with get_db_session() as session:
        res = localize_phase6b_compositions(session)
